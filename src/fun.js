function getProbabilityResponse(statement) {
    const q = String(statement || '').trim();
    if (!q) return '📊 Напиши утверждение, например: `/инфа завтра отменят физику`';
    const pct = Math.floor(Math.random() * 101);
    const barFilled = Math.round(pct / 10);
    const bar = '█'.repeat(barFilled) + '░'.repeat(10 - barFilled);
    const emoji = pct >= 80 ? '🔥' : pct >= 50 ? '⚡' : pct >= 20 ? '🤔' : '💀';
    return `📊 *${q}*\nВероятность: *${pct}%* ${emoji}\n[${bar}]`;
}

function getChoiceResponse(raw) {
    const text = String(raw || '').trim();
    if (!text) return '🎲 Напиши варианты через *или*, например: `/выбери шаурма или пицца`';
    const options = text
        .split(/\s+или\s+|\s*\|\s*/i)
        .map(s => s.trim())
        .filter(Boolean);
    if (options.length < 2) {
        return '🎲 Раздели варианты словом *или* (или знаком *|*), например: `/выбери спать или делать дз`';
    }
    const chosen = pick(options);
    return `🎲 Из ${options.length} вариантов я выбираю:\n👉 *${chosen}*`;
}

